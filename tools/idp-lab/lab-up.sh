#!/bin/bash
# Copyright 2026 Michael Still and contributors
#
# lab-up.sh -- start the identity provider lab: generate its
# credentials and certificate if they do not exist yet, bring the four
# containers up, and wait for both providers to answer.
#
# This is a development lab and not a deployment. See the README and
# docker-compose.yml beside this script for what that means.
#
# Credentials are generated here, with openssl rand, into
# ${IDP_LAB_STATE_DIR}/lab.env -- outside this repository, mode 0600,
# and regenerated only when that file does not exist. Export any
# IDP_LAB_*_PASSWORD, IDP_LAB_AUTHENTIK_API_TOKEN or
# IDP_LAB_AUTHENTIK_SECRET_KEY before the first run to choose one
# instead; the README says which.
#
# Safe to re-run: docker compose up is idempotent, the credentials are
# reused, and the certificate is only reissued once it is close to
# expiring.
#
#   tools/idp-lab/lab-up.sh

set -euo pipefail

# shellcheck source=tools/idp-lab/lab-common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lab-common.sh"

command -v docker >/dev/null 2>&1 || lab_fail 'docker is not on PATH.'
docker compose version >/dev/null 2>&1 || \
    lab_fail 'docker compose is not available (this needs the compose plugin, not docker-compose).'
command -v openssl >/dev/null 2>&1 || lab_fail 'openssl is not on PATH.'

mkdir -p "${IDP_LAB_STATE_DIR}"
chmod 0700 "${IDP_LAB_STATE_DIR}"

# One secret per line, name=value. Each is taken from the environment
# if it is set there, and generated otherwise -- so a caller who wants
# a known password exports it, and a caller who does not never sees one
# written down anywhere but this file.
if [ ! -e "${IDP_LAB_ENV_FILE}" ]; then
    lab_log "Generating credentials into ${IDP_LAB_ENV_FILE}."
    umask 077
    {
        echo '# Generated by tools/idp-lab/lab-up.sh. Throwaway credentials for a'
        echo '# loopback-only development lab. Delete this file to generate new ones.'
        echo "IDP_LAB_STATE_DIR=${IDP_LAB_STATE_DIR}"
        echo "IDP_LAB_TLS_DIR=${IDP_LAB_TLS_DIR}"
        echo "IDP_LAB_KEYCLOAK_ADMIN_USER=${IDP_LAB_KEYCLOAK_ADMIN_USER:-admin}"
        echo "IDP_LAB_KEYCLOAK_ADMIN_PASSWORD=${IDP_LAB_KEYCLOAK_ADMIN_PASSWORD:-$(openssl rand -hex 16)}"
        echo "IDP_LAB_AUTHENTIK_ADMIN_PASSWORD=${IDP_LAB_AUTHENTIK_ADMIN_PASSWORD:-$(openssl rand -hex 16)}"
        echo "IDP_LAB_AUTHENTIK_API_TOKEN=${IDP_LAB_AUTHENTIK_API_TOKEN:-$(openssl rand -hex 32)}"
        echo "IDP_LAB_AUTHENTIK_SECRET_KEY=${IDP_LAB_AUTHENTIK_SECRET_KEY:-$(openssl rand -hex 32)}"
        echo "IDP_LAB_AUTHENTIK_ADMIN_EMAIL=${IDP_LAB_AUTHENTIK_ADMIN_EMAIL:-admin@example.com}"
        echo "IDP_LAB_POSTGRES_PASSWORD=${IDP_LAB_POSTGRES_PASSWORD:-$(openssl rand -hex 16)}"
        echo "IDP_LAB_PERSON_PASSWORD=${IDP_LAB_PERSON_PASSWORD:-$(openssl rand -hex 12)}"
    } > "${IDP_LAB_ENV_FILE}"
    chmod 0600 "${IDP_LAB_ENV_FILE}"
else
    lab_log "Reusing the credentials already in ${IDP_LAB_ENV_FILE}."
fi

lab_load_env

"${IDP_LAB_DIR}/make-certificates.sh"

lab_log 'Starting the containers.'
lab_compose up --detach

# Keycloak's master realm is served as soon as it is listening, and
# Authentik's readiness endpoint only answers once the migrations its
# first boot runs have finished. Both are waited for rather than slept
# through: the migrations take minutes on a cold host and seconds on a
# warm one.
lab_wait_for_url 'Keycloak' \
    "${KEYCLOAK_URL}/realms/master/.well-known/openid-configuration" 300
lab_wait_for_url 'Authentik' "${AUTHENTIK_URL}/-/health/ready/" 600

lab_log 'Both providers are up:'
lab_log "  Keycloak admin console  ${KEYCLOAK_URL}/admin/ (user ${IDP_LAB_KEYCLOAK_ADMIN_USER})"
lab_log "  Authentik interface     ${AUTHENTIK_URL}/if/admin/ (user akadmin)"
lab_log "  credentials             ${IDP_LAB_ENV_FILE}"
lab_log 'Configure them with configure-keycloak.sh and configure-authentik.sh.'
