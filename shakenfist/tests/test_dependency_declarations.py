"""Nothing we import may rest on the generated indirect pin block.

The block between ``# START_OF_INDIRECT_DEPS`` and
``# END_OF_INDIRECT_DEPS`` in pyproject.toml is regenerated by
tools/pin-indirect-dependencies.sh from whatever the direct
dependencies happen to resolve to. A package only named there is
installed by coincidence: the day the intermediate library stops
requiring it, the reconciler drops the pin and an import of it fails,
in a repository which changed nothing.

That has a worked example in the fleet already -- shakenfist imported
oslo_concurrency in its CI harness for years because
shakenfist-utilities declared oslo.concurrency, a dependency it never
used and has since removed. This test is the local half of the fleet's
"undeclared direct dependency" audit, so the next one fails here
rather than on whichever branch is unlucky.
"""

import ast
import os
import re
import tomllib

from shakenfist.tests import base


# A copy of the source is what makes a dropped import look alive, and
# .tox alone holds tens of thousands of files we did not write.
WALK_SKIP = {
    '.cargo-cache', '.eggs', '.git', '.tox', '.venv', '__pycache__',
    'build', 'cover', 'dist', 'node_modules', 'target', 'third_party',
    'vendor', 'venv',
}

# Distributions whose import name cannot be derived from the name.
IMPORT_NAME_ALIASES = {
    'protobuf': {'google'},
    'googleapis-common-protos': {'google'},
    'grpcio': {'grpc'},
    'grpcio-health-checking': {'grpc_health'},
    'grpcio-tools': {'grpc_tools'},
    'mysqlclient': {'MySQLdb'},
    'attrs': {'attr', 'attrs'},
}


def _root():
    here = os.path.dirname(os.path.abspath(__file__))
    return os.path.dirname(os.path.dirname(here))


def _canonical(name):
    # PEP 503: "-", "_" and "." are interchangeable, case insensitively.
    return re.sub(r'[-_.]+', '-', name).lower()


def _requirement_name(requirement):
    # Strip extras, version specifiers, environment markers and
    # whitespace, leaving the distribution name.
    return re.split(r'[<>=!~;\s\[]', requirement.strip(), maxsplit=1)[0]


def _import_names(distribution):
    """The module names a distribution might plausibly install.

    Derived rather than looked up, because the audit runs against a
    checkout it has not installed: the name itself, the name with its
    separators turned into underscores, and the name with a "python" or
    "py" affix removed, so PyYAML finds yaml and python-magic finds
    magic.
    """
    canonical = _canonical(distribution)
    names = {canonical, canonical.replace('-', '_'), canonical.replace('-', '.')}
    for affix in ('python-', 'py-'):
        if canonical.startswith(affix):
            names.add(canonical[len(affix):].replace('-', '_'))
    for affix in ('-python', '-py'):
        if canonical.endswith(affix):
            names.add(canonical[:-len(affix)].replace('-', '_'))
    if canonical.startswith('py') and len(canonical) > 2:
        names.add(canonical[2:].replace('-', '_'))
    names.update(IMPORT_NAME_ALIASES.get(canonical, set()))
    return names


def _pinned_block(text):
    """The distribution names between the generated block's markers."""
    block = re.search(
        r'# START_OF_INDIRECT_DEPS\n(.*?)\n\s*# END_OF_INDIRECT_DEPS',
        text, re.DOTALL)
    if block is None:
        return None

    names = []
    for line in block.group(1).splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        quoted = re.match(r'"([^"]+)"', line)
        if quoted:
            names.append(_requirement_name(quoted.group(1)))
    return names


def _declared_above_marker(text):
    """Every distribution hand declared in the dependencies array.

    Read from the text above the marker rather than from the parsed
    array, because the parse cannot tell a hand written declaration
    from the generated copy of the same name.
    """
    above = re.search(r'\ndependencies = \[(.*?)# START_OF_INDIRECT_DEPS',
                      text, re.DOTALL)
    if above is None:
        return []

    names = []
    for line in above.group(1).splitlines():
        quoted = re.match(r'"([^"]+)"', line.strip())
        if quoted:
            names.append(_canonical(_requirement_name(quoted.group(1))))
    return names


def _declared_elsewhere(text, pyproject):
    """Every distribution declared outside the generated block.

    An optional-dependencies group counts: a test only import is still
    an import with a declaration behind it. What does not count is a
    name which appears only in the generated block, which is the whole
    question this file asks.
    """
    declared = set(_declared_above_marker(text))
    optional = pyproject.get('project', {}).get('optional-dependencies', {})
    for group in optional.values():
        for requirement in group:
            declared.add(_canonical(_requirement_name(requirement)))
    return declared


def _top_level_imports(root):
    """Every top level module name imported by our own Python."""
    imported = set()
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in WALK_SKIP]
        for filename in filenames:
            if not filename.endswith('.py'):
                continue
            path = os.path.join(dirpath, filename)
            with open(path, encoding='utf-8') as f:
                try:
                    tree = ast.parse(f.read(), filename=path)
                except SyntaxError:
                    # Deliberately malformed fixtures exist; a file we
                    # cannot parse imports nothing we can see.
                    continue
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    for alias in node.names:
                        imported.add(alias.name.split('.')[0])
                elif isinstance(node, ast.ImportFrom):
                    if node.level == 0 and node.module:
                        imported.add(node.module.split('.')[0])
    return imported


class DependencyDeclarationTestCase(base.ShakenFistTestCase):
    def setUp(self):
        super().setUp()
        self.path = os.path.join(_root(), 'pyproject.toml')
        with open(self.path, 'rb') as f:
            self.pyproject = tomllib.load(f)
        with open(self.path) as f:
            self.text = f.read()

    def test_the_generated_block_is_still_marked_out(self):
        # Every other assertion here is vacuous without the markers, and
        # a rename would otherwise turn this file green while removing
        # the thing it checks.
        pinned = _pinned_block(self.text)
        self.assertIsNotNone(
            pinned,
            'pyproject.toml no longer carries the START_OF_INDIRECT_DEPS '
            'and END_OF_INDIRECT_DEPS markers that '
            'tools/pin-indirect-dependencies.sh regenerates between.')
        self.assertNotEqual([], pinned)

    def test_no_pin_is_declared_twice(self):
        # A name in both places is two pins for one package, and Renovate
        # moves one of them (issues 3398, 3399 and 3462). The reconciler
        # leaves out anything already declared above the marker, so this
        # only happens when the generated copy is kept by hand.
        pinned = {_canonical(name) for name in _pinned_block(self.text)}
        above = _declared_above_marker(self.text)
        self.assertNotEqual([], above)

        duplicated = sorted(pinned & set(above))
        self.assertEqual(
            [], duplicated,
            '%s declared above the marker and pinned in the generated '
            'block as well. Two pins for one package break resolution as '
            'soon as Renovate bumps one of them; delete the generated '
            'copy.' % ', '.join(duplicated))

    def test_nothing_we_import_is_only_a_generated_pin(self):
        pinned = _pinned_block(self.text)
        declared = _declared_elsewhere(self.text, self.pyproject)
        imported = _top_level_imports(_root())

        # A module a declared distribution could equally have installed
        # is not evidence about a transitive one: protobuf and
        # googleapis-common-protos both install into google.
        covered = set()
        for distribution in declared:
            covered.update(_import_names(distribution))

        findings = []
        for distribution in pinned:
            names = _import_names(distribution) & imported
            if names - covered:
                findings.append(
                    '%s (imported as %s)'
                    % (distribution, ', '.join(sorted(names - covered))))

        self.assertEqual(
            [], findings,
            'these packages are imported by our own Python but declared '
            'only inside the generated indirect dependency block, where '
            'tools/pin-indirect-dependencies.sh will drop them as soon as '
            'nothing else requires them: %s. Declare each above the '
            '# START_OF_INDIRECT_DEPS marker, at the version it currently '
            'resolves to, and delete the generated copy.'
            % '; '.join(sorted(findings)))

    def test_annotated_types_is_declared_directly(self):
        # The worked example this file was written for: the schema tests
        # import annotated_types, which arrived only because pydantic
        # requires it (issue 5038). pydantic's requirement is a floor
        # rather than an exact pin, so it is free to move or go.
        self.assertIn(
            'annotated-types', _declared_above_marker(self.text),
            'annotated_types is imported by the schema tests, so it is '
            'declared in pyproject.toml above the generated block rather '
            "than left to arrive as pydantic's requirement.")
